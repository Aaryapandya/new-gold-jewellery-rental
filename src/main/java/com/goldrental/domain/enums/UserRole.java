package com.goldrental.domain.enums;

/**
 * Defines the roles available to platform users.
 *
 * <p>BUYER  – can discover and rent jewellery.</p>
 * <p>SUPPLIER – can list jewellery and manage bookings.</p>
 * <p>ADMIN  – platform administrator with full access.</p>
 */
public enum UserRole {
    BUYER,
    SUPPLIER,
    ADMIN
}
